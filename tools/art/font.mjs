export const FONT = { cellWidth: 8, cellHeight: 12, first: 32, lineHeight: 12, top: 3 };

export function buildFont() {
  const cols = 16, n = 95;
  const img = new Canvas(cols * 8, Math.ceil(n / cols) * 12);
  const widths = {};
  for (let i = 0; i < n; i++) {
    const ch = String.fromCharCode(32 + i);
    const g = G[ch];
    if (!g) throw new Error('missing glyph ' + ch);
    const w = Math.max(...g.map((r) => r.length));
    widths[ch] = w + 1;
    const cx = (i % cols) * 8, cy = Math.floor(i / cols) * 12;
    const cell = new Canvas(8, 12);
    g.forEach((row, r) => [...row].forEach((c, x) => { if (c === '#') cell.set(x, FONT.top + r, P.white); }));
    cell.dropShadow(1, 1, P.ink);
    img.blit(cell, cx, cy, { blend: false });
  }
  const json = { cellWidth: 8, cellHeight: 12, first: 32, lineHeight: 12, baseline: 9, widths };
  return { img, json };
}

/** Draw text with the built font (for previews). */
export function drawText(target, font, text, x, y, color = null) {
  let cx = x;
  for (const ch of text) {
    const i = ch.charCodeAt(0) - 32;
    if (i < 0 || i > 94) continue;
    const src = font.img.crop((i % 16) * 8, Math.floor(i / 16) * 12, 8, 12);
    if (color != null) src.recolor((c) => (c === P.white ? color : c));
    target.blit(src, cx, y);
    cx += font.json.widths[ch];
  }
  return cx - x;
}
